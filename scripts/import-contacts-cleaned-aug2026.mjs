// Import Oleksandr's cleaned contact list (GT-Contacts+John-Merged.xlsx,
// shared 2026-08-17) into the live CRM. The sheet is the freshest source for
// contact name / job title / email / LinkedIn, keyed on the HubSpot Record ID
// (= contacts.legacy_id), so where the sheet has a value it WINS over what the
// June import left behind; empty sheet cells keep the existing value.
//
// The XLSX is converted to CSV first (openpyxl one-liner, keep the header):
//   Record ID, First Name, Last Name, Job Title, Email, LinkedIn Page,
//   Company Name, Contact owner
//
// Run: bun run scripts/import-contacts-cleaned-aug2026.mjs \
//        <contacts-cleaned.csv> <deals-aug.csv>
//   deals-aug.csv = hubspot-crm-exports-all-deals-2026-08-11.csv, used to map
//   each deal to its primary contact so the refreshed titles/LinkedIn land on
//   the deal records too.
//   out: supabase/seed/contacts-cleaned-aug2026.sql   (apply with psql -f)
//        supabase/seed/contacts-cleaned-aug2026-report.md
//
// What the generated SQL does:
//   A) insert contacts that are in the sheet but not in the CRM
//   B) refresh name/title/email/linkedin on existing contacts (sheet wins
//      where filled — that's the point of the cleanup round)
//   C) link contacts to companies by the cleaned company name, fill-only and
//      skipping ambiguous duplicate company names (Oleksandr's "companies
//      with no contacts" observation)
//   D) refresh each deal's primary-contact fields from its contact
//   The "Removed" sheet is NOT acted on — deletion needs an explicit call.
import { readFileSync, writeFileSync } from "node:fs";

const [contactsPath, dealsPath] = process.argv.slice(2);
if (!dealsPath) {
  console.error(
    "usage: bun run scripts/import-contacts-cleaned-aug2026.mjs <contacts-cleaned.csv> <deals-aug.csv>",
  );
  process.exit(1);
}

// --- RFC4180-ish CSV parser (same as the sibling import scripts) ---
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let i = 0;
  let inQuotes = false;
  while (i < text.length) {
    const ch = text[i];
    if (inQuotes) {
      if (ch === '"') {
        if (text[i + 1] === '"') { field += '"'; i += 2; continue; }
        inQuotes = false; i++; continue;
      }
      field += ch; i++; continue;
    }
    if (ch === '"') { inQuotes = true; i++; continue; }
    if (ch === ",") { row.push(field); field = ""; i++; continue; }
    if (ch === "\r") { i++; continue; }
    if (ch === "\n") { row.push(field); rows.push(row); row = []; field = ""; i++; continue; }
    field += ch; i++;
  }
  if (field.length || row.length) { row.push(field); rows.push(row); }
  const header = rows.shift();
  return rows
    .filter((r) => r.length > 1 || (r.length === 1 && r[0] !== ""))
    .map((r) => Object.fromEntries(header.map((h, j) => [h.trim(), (r[j] ?? "").trim()])));
}

const sq = (v) =>
  v === null || v === undefined || v === ""
    ? "null"
    : `'${String(v).replace(/'/g, "''")}'`;

const OWNER_CODE = {
  "Andy Baynes": "AB",
  "Anastasiia Romasiuk": "AR",
  "Daria Konoval": "DK",
  "Ilya Ponomarenko": "IP",
  "John Harris": "JH",
  "Jordan Orloff": "JO",
  "Mariana Kurylo": "MK",
  "Mariia Atrasevych": "MA",
  "Michael Bayler": "MB",
  "Nataliia Eksarova": "NE",
  "Nikita Gorskykh": "NG",
  "Oleksandr Kicha": "OK",
  "Victoria Shvets": "VS",
  "Vlad Solovei": "VO",
};
const ownerCode = (raw) => {
  const name = (raw ?? "").replace(/\s*\(Deactivated User\)\s*/i, "").trim();
  return name ? (OWNER_CODE[name] ?? null) : null;
};

const chunk = (arr, n) =>
  Array.from({ length: Math.ceil(arr.length / n) }, (_, i) => arr.slice(i * n, i * n + n));

const semiList = (v) => (v ?? "").split(";").map((x) => x.trim()).filter(Boolean);

function normLinkedin(v) {
  let u = (v ?? "").trim();
  if (!u) return null;
  if (!/^https?:\/\//i.test(u)) u = "https://" + u.replace(/^\/+/, "");
  return /linkedin\./i.test(u) ? u : null;
}

// ---------- load ----------
const contacts = parseCsv(readFileSync(contactsPath, "utf8"));
const deals = parseCsv(readFileSync(dealsPath, "utf8"));

const sheet = contacts
  .map((c) => ({
    lid: c["Record ID"],
    name: [c["First Name"], c["Last Name"]].filter(Boolean).join(" ").trim() || null,
    title: c["Job Title"] || null,
    email: c["Email"] || null,
    linkedin: normLinkedin(c["LinkedIn Page"]),
    company: (c["Company Name"] ?? "").trim().toLowerCase() || null,
    owner: ownerCode(c["Contact owner"]),
  }))
  .filter((c) => /^\d+$/.test(c.lid));

// deal -> primary (first) associated contact, from the Aug deals export
const primaryOf = [];
for (const d of deals) {
  const ids = semiList(d["Associated Contact IDs"]);
  if (ids.length) primaryOf.push({ dealLid: d["Record ID"], contactLid: ids[0] });
}

// ---------- build SQL ----------
let out = `-- AUTO-GENERATED by scripts/import-contacts-cleaned-aug2026.mjs — see
-- that file for the mapping decisions. Keyed on legacy_id; safe to re-apply.
begin;

`;

// A) contacts in the sheet but not yet in the CRM
out += `-- A) contacts new to the CRM (sheet rows whose Record ID is unknown)\n`;
out += `insert into public.contacts (legacy_id, name, title, email, linkedin_url, stage, owner_code)\nselect * from (values\n`;
out += sheet
  .map(
    (c, i) =>
      `  (${c.lid}${i === 0 ? "::bigint" : ""}, ${sq(c.name)}, ${sq(c.title)}, ${sq(c.email)}, ${sq(
        c.linkedin,
      )}, 'connection'${i === 0 ? "::text" : ""}, ${sq(c.owner)})`,
  )
  .join(",\n");
out += `\n) as v(legacy_id, name, title, email, linkedin_url, stage, owner_code)
where not exists (select 1 from public.contacts c where c.legacy_id = v.legacy_id);\n\n`;

// B) refresh existing contacts — the cleaned sheet wins where it has a value
out += `-- B) name/title/email/linkedin refresh (sheet wins where filled)\n`;
for (const batch of chunk(sheet, 500)) {
  out += `update public.contacts c
set name         = coalesce(nullif(v.name, ''), c.name),
    title        = coalesce(nullif(v.title, ''), c.title),
    email        = coalesce(nullif(v.email, ''), c.email),
    linkedin_url = coalesce(nullif(v.linkedin, ''), c.linkedin_url)
from (values\n`;
  out += batch
    .map(
      (c, i) =>
        `  (${c.lid}${i === 0 ? "::bigint" : ""}, ${sq(c.name)}, ${sq(c.title)}, ${sq(c.email)}, ${sq(c.linkedin)})`,
    )
    .join(",\n");
  out += `\n) as v(legacy_id, name, title, email, linkedin)\nwhere c.legacy_id = v.legacy_id;\n\n`;
}

// C) company links from the cleaned company names (fill-only, unambiguous)
const withCompany = sheet.filter((c) => c.company);
out += `-- C) contact -> company by cleaned company name (${withCompany.length} candidates)\n`;
for (const batch of chunk(withCompany, 500)) {
  out += `update public.contacts c
set company_id = co.id
from (values\n`;
  out += batch.map((x, i) => `  (${x.lid}${i === 0 ? "::bigint" : ""}, ${sq(x.company)})`).join(",\n");
  out += `\n) as v(legacy_id, cname), public.companies co
where c.legacy_id = v.legacy_id
  and c.company_id is null
  and lower(btrim(co.name)) = v.cname
  and not exists (
    select 1 from public.companies co2
    where lower(btrim(co2.name)) = v.cname and co2.id <> co.id
  );\n\n`;
}

// D) carry the refreshed contact data onto each deal's primary-contact fields
out += `-- D) deals: primary contact refresh (${primaryOf.length} deals)\n`;
for (const batch of chunk(primaryOf, 500)) {
  out += `update public.deals d
set contact_name = coalesce(nullif(c.name, ''), d.contact_name),
    title        = coalesce(nullif(c.title, ''), d.title),
    email        = coalesce(nullif(c.email, ''), d.email),
    linkedin_url = coalesce(nullif(c.linkedin_url, ''), d.linkedin_url)
from (values\n`;
  out += batch
    .map((r, i) => `  (${r.dealLid}${i === 0 ? "::bigint" : ""}, ${r.contactLid}${i === 0 ? "::bigint" : ""})`)
    .join(",\n");
  out += `\n) as v(deal_lid, contact_lid), public.contacts c
where d.legacy_id = v.deal_lid
  and c.legacy_id = v.contact_lid;\n\n`;
}

out += `commit;\n`;

writeFileSync(new URL("../supabase/seed/contacts-cleaned-aug2026.sql", import.meta.url), out);

const report = `# Cleaned contact list import — Aug 2026

Source: \`GT-Contacts+John-Merged.xlsx\` (Oleksandr, 2026-08-17), keyed on the
HubSpot Record ID. The sheet wins over June-import data wherever it has a
value; blanks keep what's in the CRM.

- ${sheet.length} sheet contacts processed (${sheet.filter((c) => c.title).length} titles,
  ${sheet.filter((c) => c.linkedin).length} LinkedIn URLs, ${sheet.filter((c) => c.email).length} emails).
- Contacts not yet in the CRM are inserted; existing ones refreshed in place.
- ${withCompany.length} contacts carry a company name — linked to the company book
  where the name matches exactly one company and the contact had no link yet.
- ${primaryOf.length} deals get their primary-contact fields refreshed from the
  cleaned data (name, title, email, LinkedIn).

## Not acted on

- The workbook's "Removed" sheet (109 contacts with IDs still in the CRM) is
  ignored — deleting people needs an explicit decision, and some may be
  referenced by deals/notes. Say the word and a follow-up can archive them.
`;
writeFileSync(new URL("../supabase/seed/contacts-cleaned-aug2026-report.md", import.meta.url), report);

