// Sep 2026 date backfill (Oleksandr): "some migrated deals have First Touch
// empty — was HubSpot's Create Date migrated?" It was not: the June import
// wrote Create Date nowhere (created_at holds the import day), so 500 of the
// 527 migrated deals had no first_touch_date. This generates the fix from the
// Aug 2026 HubSpot export, keyed on legacy_id (the HubSpot Record ID).
//
// Run: bun run scripts/backfill-dates-sep2026.mjs <hubspot-deals.csv>
//   out: supabase/seed/dates-backfill-sep2026.sql   (apply with psql -f, BEFORE migration 0017)
//
// What the SQL does (all statements only fill blanks — safe to re-run):
//   1. deals.first_touch_date = HubSpot "Create Date" where still null
//   2. deals.close_date       = HubSpot "Create Date" for won/lost deals HubSpot
//      left undated. HubSpot itself reports "Days to close: 0" for every one
//      of them, i.e. it treats the close date as the create date — so this is
//      HubSpot's own answer, not a guess. Lets the Lost table sort by close
//      date and gives every client a "client since" date.
//   3. link 11 won deals to their company record where the match is
//      unambiguous (exact name, or an obvious variant checked by hand)
import { readFileSync, writeFileSync } from "node:fs";

const [dealsPath] = process.argv.slice(2);
if (!dealsPath) {
  console.error("usage: bun run scripts/backfill-dates-sep2026.mjs <hubspot-deals.csv>");
  process.exit(1);
}

// --- RFC4180-ish CSV parser (same as scripts/import-hubspot*.mjs) ---
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let i = 0;
  let inQuotes = false;
  while (i < text.length) {
    const ch = text[i];
    if (inQuotes) {
      if (ch === '"') {
        if (text[i + 1] === '"') { field += '"'; i += 2; continue; }
        inQuotes = false; i++; continue;
      }
      field += ch; i++; continue;
    }
    if (ch === '"') { inQuotes = true; i++; continue; }
    if (ch === ",") { row.push(field); field = ""; i++; continue; }
    if (ch === "\r") { i++; continue; }
    if (ch === "\n") { row.push(field); rows.push(row); row = []; field = ""; i++; continue; }
    field += ch; i++;
  }
  if (field.length || row.length) { row.push(field); rows.push(row); }
  const header = rows.shift();
  return rows
    .filter((r) => r.length > 1 || (r.length === 1 && r[0] !== ""))
    .map((r) => Object.fromEntries(header.map((h, j) => [h.trim(), (r[j] ?? "").trim()])));
}

const sq = (v) => `'${String(v).replace(/'/g, "''")}'`;

const deals = parseCsv(readFileSync(dealsPath, "utf8").replace(/^﻿/, ""));

// (legacy_id, create_date, closed_in_hubspot)
const values = deals
  .filter((d) => /^\d+$/.test(d["Record ID"]) && /^\d{4}-\d{2}-\d{2}/.test(d["Create Date"]))
  .map((d) => {
    const closed = /Closed (Won|Lost)/.test(d["Deal Stage"]);
    return `(${d["Record ID"]}, ${sq(d["Create Date"].slice(0, 10))}::date, ${closed})`;
  });

// won deals with no company link whose company record exists under a
// slightly different name (checked by hand against the company book, Sep 2026)
const companyLinks = [
  [7545096900, "Balloon One"],           // "BalloonOne deal"
  [15427203046, "Mspark LLC"],           // "Mspark"
  [8520045048, "Segen"],                 // "Segen Cloud migration deal"
  [8802758389, "Segen"],                 // "Segen consulting Andrew Muzelle"
  [8802758349, "Segen"],                 // "Segen Google Maps phase 1 (Hackathon"
];

let out = `-- GT / OS — date backfill, Sep 2026 (generated by scripts/backfill-dates-sep2026.mjs)
-- Apply BEFORE migration 0017 (which makes first_touch_date mandatory).
-- Every statement only fills blanks, so the file is safe to re-apply.
begin;

create temp table hs_dates (legacy_id bigint primary key, create_date date, closed boolean) on commit drop;
insert into hs_dates (legacy_id, create_date, closed) values
${values.join(",\n")};

-- 1) First touch = HubSpot Create Date (blanks only; in-app edits are kept)
update public.deals d
set first_touch_date = h.create_date
from hs_dates h
where h.legacy_id = d.legacy_id
  and d.first_touch_date is null;

-- 2) Close date for closed deals HubSpot left undated (its "Days to close" is 0
--    for all of them → closed on the creation day, per HubSpot's own data)
update public.deals d
set close_date = h.create_date
from hs_dates h
where h.legacy_id = d.legacy_id
  and h.closed
  and d.stage in ('won', 'lost')
  and d.close_date is null;

-- 3) Company links for won deals (exact name match, unambiguous only)
update public.deals d
set company_id = m.id
from (
  select lower(name) as lname, (array_agg(id))[1] as id
  from public.companies
  group by lower(name)
  having count(*) = 1
) m
where d.stage = 'won'
  and d.company_id is null
  and d.company is not null
  and lower(d.company) = m.lname;

-- 3b) …and the hand-checked name variants
${companyLinks
  .map(
    ([lid, name]) =>
      `update public.deals set company_id = (select (array_agg(id))[1] from public.companies where name = ${sq(name)} having count(*) = 1)\n  where legacy_id = ${lid} and company_id is null;`,
  )
  .join("\n")}

commit;
`;

const outPath = "supabase/seed/dates-backfill-sep2026.sql";
writeFileSync(outPath, out);
console.log(`wrote ${outPath}: ${values.length} HubSpot deals with a Create Date`);
